/**
 * Writers for the files the mod plays during capture (content/hqminimap/):
 *   cutscenes/mosaic_run_pXX.lua — one CameraFrame cutscene per pitch (pitch is frozen per
 *                                  playCutscene), one 4-keyframe hold per tile;
 *   mosaic_plan.lua             — lattice + timings read by capture.lua and by TileLab.
 * Output is byte-identical to the miniMapper reference generator, comment lines aside
 * (test/plan.test.ts).
 */
import type { Mosaic, MosaicConfig } from "./geometry";
import { fmtF, fmtG } from "./pyfmt";

/** CameraFrame nadir pitch (−4.5π − 3.3e-5; probe-locked, see docs/agent-memory). */
export const NADIR_PITCH = -14.1372;
export const CUTSCENE_PREFIX = "hqminimap::/hqminimap/cutscenes/mosaic_run_p";
/** Seconds per tile segment (1 s was the validated reference; 25 % slower since the game skipped tiles, HQ-044). */
export const SEG_DUR = 1.25;
/** Screenshot time inside the stationary hold [HOLD_EPS, SEG_DUR − TRANSIT − HOLD_EPS] (scaled with SEG_DUR). */
export const SHOT_OFFSET = 0.3125;
/** Duplicate keyframe spacing at each end of a hold. */
export const HOLD_EPS = 0.02;
/** Seconds between hold end and next tile. */
export const TRANSIT = 0.05;
/** Seconds after capture lighting before the first playCutscene. */
export const ENV_SETTLE_SEC = 2;
const ANGLE = 0;
const PAD = 0;

export interface CaptureTiming {
  segDur: number;
  shotOffset: number;
  envSettleSec: number;
}

/** Timing presets offered in GridLab ("normal" = the validated reference timings). */
export const CAPTURE_PRESETS: Record<"normal" | "fast" | "fastest", CaptureTiming> = {
  normal: { segDur: SEG_DUR, shotOffset: SHOT_OFFSET, envSettleSec: ENV_SETTLE_SEC },
  fast: { segDur: 0.5, shotOffset: 0.2, envSettleSec: 1 },
  fastest: { segDur: 0.25, shotOffset: 0.12, envSettleSec: 0.5 },
};
/** Shortest tile segment accepted (s). */
export const MIN_SEG_DUR = 0.05;

/**
 * Transit and hold margins of a segment: the reference values, scaled down for segments shorter
 * than 0.25 s (otherwise no still hold would be left).
 */
export const transitOf = (segDur: number) => (segDur >= 0.25 ? TRANSIT : segDur * 0.2);
export const holdEpsOf = (segDur: number) => (segDur >= 0.25 ? HOLD_EPS : segDur * 0.05);

/** Timing of a config (reference constants when not set). */
export function captureTiming(cfg: MosaicConfig): CaptureTiming {
  return {
    segDur: cfg.SEG_DUR ?? SEG_DUR,
    shotOffset: cfg.SHOT_OFFSET ?? SHOT_OFFSET,
    envSettleSec: cfg.ENV_SETTLE_SEC ?? ENV_SETTLE_SEC,
  };
}

export type TimingIssue =
  | { kind: "segTooShort"; min: number }
  | { kind: "shotOutsideHold"; min: number; max: number }
  | { kind: "negativeSettle" };

/** Why this timing cannot be written (null = OK): the shot must fall inside the still hold. */
export function timingIssue(t: CaptureTiming): TimingIssue | null {
  if (!(t.segDur >= MIN_SEG_DUR)) return { kind: "segTooShort", min: MIN_SEG_DUR };
  const eps = holdEpsOf(t.segDur);
  const max = Math.round((t.segDur - transitOf(t.segDur) - eps) * 1000) / 1000;
  if (!(t.shotOffset >= eps && t.shotOffset <= max)) return { kind: "shotOutsideHold", min: eps, max };
  if (!(t.envSettleSec >= 0)) return { kind: "negativeSettle" };
  return null;
}

/** Whole capture duration (s): lighting settle + one segment per tile. */
export function captureDurationSec(t: CaptureTiming, tiles: number): number {
  return t.envSettleSec + tiles * t.segDur;
}

export interface PlanMeta {
  terrainSource: string;
  zRefSource?: string;
  fovScaleSource?: string;
  generator?: string;
}

function keyframe(t: number, x: number, y: number, z: number, pitch: number, key: number): string {
  return (
    "\tcamera[#camera+1]={" +
    `time=${fmtF(t, 3)},position={${fmtF(x, 4)},${fmtF(y, 4)},${fmtF(z, 4)}},` +
    `pitch=${fmtF(pitch, 8)},angle=${fmtF(ANGLE, 4)},roll=0,fovY=${fmtG(key, 10)},` +
    "skyRotation=0,speed=1}"
  );
}

/** mosaic_run_pXX.lua for one pitch. */
export function renderCutscene(mo: Mosaic, pitch = NADIR_PITCH, pitchIdx = 1,
  generator = "HQminiMap GridLab"): string {
  const cfg = mo.config, g = mo.geo;
  const lines = [
    `-- Auto-generated by ${generator} (pinhole_v3, fovY=${fmtG(mo.key, 10)} rad ` +
      `-> fovV=${fmtF(g.fovV, 4)}/fovH=${fmtF(g.fovH, 4)}, pixelAspect=${fmtG(cfg.PIXEL_ASPECT, 6)}).`,
    `-- Pitch #${pitchIdx} = ${fmtG(pitch, 10)}; grid ${cfg.GRID_NX}x${cfg.GRID_NY}; ` +
      `Z_eye=${fmtF(cfg.Z_EYE, 0)} Z_ref=${fmtF(mo.zRef, 3)} h=${fmtF(g.h, 3)}; ` +
      `step=${fmtF(mo.stepX, 4)}x${fmtF(mo.stepY, 4)}.`,
    "-- Do not hand-edit: change the grid in HQminiMap (GridLab) and schedule the scan again.",
    "function data()",
    "\tlocal camera = {}",
  ];
  const { segDur } = captureTiming(cfg);
  const holdEnd = segDur - transitOf(segDur), eps = holdEpsOf(segDur);
  mo.centers.forEach((c, seg) => {
    const t0 = seg * segDur;
    // 4 identical keys: the middle segment [t0+eps, t0+holdEnd-eps] has zero tangents.
    for (const t of [t0, t0 + eps, t0 + holdEnd - eps, t0 + holdEnd]) {
      lines.push(keyframe(t, c.x, c.y, cfg.Z_EYE, pitch, mo.key));
    }
  });
  if (mo.centers.length) {
    const last = mo.centers[mo.centers.length - 1];
    lines.push(keyframe(mo.centers.length * segDur, last.x, last.y, cfg.Z_EYE, pitch, mo.key));
  }
  lines.push('\treturn {camera=camera,fades={},music="",portraits={},subtitles={},voiceOvers={}}');
  lines.push("end");
  lines.push("");
  return lines.join("\n");
}

/** mosaic_plan.lua. */
export function renderPlan(mo: Mosaic, meta: PlanMeta, pitches: number[] = [NADIR_PITCH]): string {
  const cfg = mo.config, g = mo.geo;
  const Z = cfg.Z_EYE;
  const tm = captureTiming(cfg);
  const pitchLines = pitches.map((p, i) => `\t[${i + 1}] = ${fmtG(p, 10)},`).join("\n");
  const centerLines = mo.centers
    .map((c, i) => `\t[${i + 1}] = { x = ${fmtF(c.x, 4)}, y = ${fmtF(c.y, 4)}, z = ${fmtF(Z, 4)} },`)
    .join("\n");
  const list = (vals: number[], f: (v: number) => string) => vals.map(f).join(", ");
  return (
    `-- Auto-generated by ${meta.generator ?? "HQminiMap GridLab"} — do not hand-edit.\n` +
    "-- Loaded by hqminimap capture.lua (pinhole_v3; cols=nY, rows=nX) and by TileLab.\n" +
    "local M = {}\n" +
    `M.nX = ${cfg.GRID_NX}\n` +
    `M.nY = ${cfg.GRID_NY}\n` +
    `M.dist = ${fmtG(Z, 6)}\n` +
    `M.zEye = ${fmtG(Z, 6)}\n` +
    `M.zRef = ${fmtG(mo.zRef, 8)}\n` +
    `M.zRefSource = "${meta.zRefSource ?? "map_median"}"\n` +
    `M.h = ${fmtG(g.h, 8)}\n` +
    `M.segDur = ${fmtG(tm.segDur, 6)}\n` +
    `M.shotOffset = ${fmtG(tm.shotOffset, 6)}\n` +
    `M.holdEps = ${fmtG(holdEpsOf(tm.segDur), 6)}\n` +
    `M.transit = ${fmtG(transitOf(tm.segDur), 6)}\n` +
    `M.envSettleSec = ${fmtG(tm.envSettleSec, 6)}\n` +
    (cfg.SPEED_PRESET ? `M.speedPreset = "${cfg.SPEED_PRESET}"\n` : "") +
    `M.fovY = ${fmtG(mo.key, 10)}\n` +
    `M.fovVDeg = ${fmtG(cfg.FOV_V_DEG, 10)}\n` +
    `M.fovScale = ${fmtG(cfg.FOV_SCALE, 10)}\n` +
    `M.fovScaleSource = "${meta.fovScaleSource ?? "constant"}"\n` +
    `M.pixelAspect = ${fmtG(cfg.PIXEL_ASPECT, 8)}\n` +
    `M.fovV = ${fmtG(g.fovV, 8)}\n` +
    `M.fovYEff = ${fmtG(g.fovV, 8)}\n` +
    `M.fovH = ${fmtG(g.fovH, 8)}\n` +
    `M.pitchCount = ${pitches.length}\n` +
    "M.pitches = {\n" +
    `${pitchLines}\n` +
    "}\n" +
    `M.cutscenePathPrefix = "${CUTSCENE_PREFIX}"\n` +
    `M.screenW = ${fmtG(cfg.screenW, 6)}\n` +
    `M.screenH = ${fmtG(cfg.screenH, 6)}\n` +
    `M.viewW = ${fmtG(g.viewY, 8)}\n` +
    `M.viewH = ${fmtG(g.viewX, 8)}\n` +
    `M.gsdX = ${fmtG(g.gsdX, 8)}\n` +
    `M.gsdY = ${fmtG(g.gsdY, 8)}\n` +
    `M.stepScaleX = ${fmtG(cfg.STEP_SCALE_X, 8)}\n` +
    `M.stepScaleY = ${fmtG(cfg.STEP_SCALE_Y, 8)}\n` +
    `M.stepX = ${fmtG(mo.stepX, 8)}\n` +
    `M.stepY = ${fmtG(mo.stepY, 8)}\n` +
    `M.tileW = ${fmtG(mo.stepX, 8)}\n` +
    `M.tileH = ${fmtG(mo.stepY, 8)}\n` +
    `M.pad = ${fmtG(PAD, 6)}\n` +
    `M.mapCx = ${fmtG(mo.mapCx, 6)}\n` +
    `M.mapCy = ${fmtG(mo.mapCy, 6)}\n` +
    `M.terrainSource = "${meta.terrainSource}"\n` +
    `M.captureTimeSec = ${fmtG(cfg.CAPTURE_TIME_SEC, 6)}\n` +
    `M.captureDayOfYear = ${fmtG(cfg.CAPTURE_DAY_OF_YEAR, 6)}\n` +
    `M.captureLatitude = ${fmtG(cfg.CAPTURE_LATITUDE, 6)}\n` +
    `M.sunZenithDeg = ${fmtG(mo.sunZenith, 6)}\n` +
    `M.maxViewAngleDeg = ${fmtG(mo.maxView, 6)}\n` +
    `M.overlapPctX = { ${list(mo.overlapX, (v) => fmtF(v, 3))} }\n` +
    `M.overlapPctY = { ${list(mo.overlapY, (v) => fmtF(v, 3))} }\n` +
    `M.seamMode = "${mo.seamMode}"\n` +
    "-- Ground z per seam (X: between rows ix/ix+1, Y: between cols iy/iy+1).\n" +
    `M.seamZX = { ${list(mo.seamZX, (z) => fmtF(z, 6))} }\n` +
    `M.seamZY = { ${list(mo.seamZY, (z) => fmtF(z, 6))} }\n` +
    "-- Exact keyframe XY per segment (seg = iy*nX + ix + 1).\n" +
    "M.centers = {\n" +
    `${centerLines}\n` +
    "}\n" +
    'M.viewSource = "pinhole_v3"\n' +
    "return M\n"
  );
}

/** File name of the cutscene for pitch index (1-based). */
export function cutsceneFileName(pitchIdx: number): string {
  return `mosaic_run_p${String(pitchIdx).padStart(2, "0")}.lua`;
}
